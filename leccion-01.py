# --- print(): muestra cosas en pantalla ---
print("¡Hola! Este es mi primer programa.")


# --- Variables: cajitas con nombre que guardan datos ---

# Una variable de TEXTO (se escribe entre comillas):
mi_nombre = "Luna Sol"

# Una variable de NÚMERO (sin comillas):
mi_edad = 21

# Variable NUEVA que añadimos: tu ciudad
mi_ciudad = "Eivissa"

# Ahora las mostramos en pantalla:
print("Me llamo:")
print(mi_nombre)
print("Y tengo esta edad:")
print(mi_edad)
print("Vivo en:")
print(mi_ciudad)


